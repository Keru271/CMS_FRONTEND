  const [campaignPage, setCampaignPage] = useState(1);
  const [campaignPageSize, setCampaignPageSize] = useState(10);
  const [cartPage, setCartPage] = useState(1);
  const [cartPageSize, setCartPageSize] = useState(10);

  const [activePixelGuide, setActivePixelGuide] = useState<PixelGuide | null>(null);

  // Campaign Modal
  const [isCampaignModalOpen, setIsCampaignModalOpen] = useState(false);
  const [campaignForm, setCampaignForm] = useState<{
    title: string;
    channel: MarketingChannel;
    targetSegment: string;
    subject: string;
    body: string;
    templateId?: string;
  }>({
    title: '',
    channel: 'EMAIL',
    targetSegment: 'All Subscribers',
    subject: '',
    body: '',
    templateId: '',
  });

  // UTM Builder State
  const [utmUrl, setUtmUrl] = useState('');
  const [utmSource, setUtmSource] = useState('');
  const [utmMedium, setUtmMedium] = useState('');
  const [utmCampaign, setUtmCampaign] = useState('');
  const [utmTerm, setUtmTerm] = useState('');
  const [utmContent, setUtmContent] = useState('');
  const [copiedUtm, setCopiedUtm] = useState(false);

  // Email Test Dispatch State
  const [testRecipientEmail, setTestRecipientEmail] = useState('');
  const [isSendingTest, setIsSendingTest] = useState(false);

  const [isSaving, setIsSaving] = useState(false);

  useEffect(() => {
    loadData();
  }, []);

  const loadData = async () => {
    setIsLoading(true);
    try {
      const [campData, pixData, cartData, templatesData] = await Promise.all([
        cmsService.getMarketingCampaigns(),
        cmsService.getPixelConfig(),
        cmsService.getAbandonedCarts(),
        cmsService.getEmailTemplates().catch(() => []),
      ]);
      setCampaigns(campData);
      setPixelConfig(pixData);
      setAbandonedCarts(cartData);
      const rawTemplates = Array.isArray(templatesData)
        ? templatesData
        : (templatesData as any)?.templates || [];
      setEmailTemplates(rawTemplates);
    } catch (err) {
      console.error('Failed to load marketing data:', err);
    } finally {
      setIsLoading(false);
    }
  };

  const showToast = (text: string, type: 'success' | 'error' = 'success') => {
    setToastMessage({ text, type });
    setTimeout(() => setToastMessage(null), 4000);
  };

  // CAMPAIGN CREATION
  const handleOpenCreateCampaign = (channel: MarketingChannel = 'EMAIL') => {
    let initialTitle = '';
    let initialSubject = '';
    let initialBody = 'Explore our latest collections and enjoy exclusive discounts on your order today!';
    let initialTemplateId = '';

    if (channel === 'WHATSAPP') {
      const waPreset = WHATSAPP_TEMPLATE_PRESETS[0];
      initialTitle = waPreset.name;
      initialSubject = waPreset.subject;
      initialBody = waPreset.body;
      initialTemplateId = waPreset.id;
    } else if (channel === 'SMS') {
      const smsPreset = SMS_TEMPLATE_PRESETS[0];
      initialTitle = smsPreset.name;
      initialSubject = smsPreset.subject;
      initialBody = smsPreset.body;
      initialTemplateId = smsPreset.id;
    } else {
      const defaultTmpl = emailTemplates.find((t) => t.category === 'MARKETING') || emailTemplates[0];
      initialTitle = defaultTmpl?.name || '';
      initialSubject = defaultTmpl?.subject || '🔥 Special Offer Just for You!';
      initialTemplateId = defaultTmpl?.id || '';
    }

    setCampaignForm({
      title: initialTitle,
      channel,
      targetSegment: 'All Customers',
      subject: initialSubject,
      body: initialBody,
      templateId: initialTemplateId,
    });
    setIsCampaignModalOpen(true);
  };

  const handleSelectTemplate = (templateId: string) => {
    if (!templateId) {
      setCampaignForm((prev) => ({ ...prev, templateId: '' }));
      return;
    }
    const t = emailTemplates.find((tmpl) => tmpl.id === templateId);
    if (t) {
      setCampaignForm((prev) => ({
        ...prev,
        templateId,
        title: prev.title || t.name,
        subject: t.subject || prev.subject,
      }));
    }
  };

  const handleSaveCampaign = async (e: React.FormEvent) => {
    e.preventDefault();
    setIsSaving(true);
    try {
      const created = await cmsService.createMarketingCampaign({
        title: campaignForm.title,
        channel: campaignForm.channel,
        targetSegment: campaignForm.targetSegment,
        subject: campaignForm.subject,
        body: campaignForm.body,
        templateId: campaignForm.templateId || undefined,
        status: 'SENT',
      });

      showToast(`Marketing broadcast "${created.title}" sent successfully!`, 'success');
      setIsCampaignModalOpen(false);
      await loadData();
    } catch (err: any) {
      showToast(err.message || 'Failed to send broadcast.', 'error');
    } finally {
      setIsSaving(false);
    }
  };

  const handleSendCampaignTest = async () => {
    if (!testRecipientEmail || !testRecipientEmail.includes('@')) {
      showToast('Please enter a valid recipient email for the test.', 'error');
      return;
    }
    setIsSendingTest(true);
    try {
      const res = await cmsService.sendMarketingCampaignTestEmail({
        recipientEmail: testRecipientEmail.trim(),
        title: campaignForm.title || 'Special Announcement',
        subject: campaignForm.subject || campaignForm.title,
        body: campaignForm.body || '',
        templateId: campaignForm.templateId || undefined,
      });
      showToast(res.message || `Test email dispatched to ${testRecipientEmail}!`, 'success');
    } catch (err: any) {
      showToast(err.message || 'Failed to dispatch test email.', 'error');
    } finally {
      setIsSendingTest(false);
    }
  };

  const handleDeleteCampaign = async (id: string) => {
    try {
      setIsSaving(true);
      await cmsService.deleteMarketingCampaign(id);
      showToast('Campaign deleted.', 'success');
      await loadData();
    } catch (err: any) {
      showToast(err.message || 'Failed to delete campaign.', 'error');
    } finally {
      setIsSaving(false);
    }
  };

  // CART RECOVERY
  const handleSendRecovery = async (id: string) => {
    try {
      setIsSaving(true);
      const updated = await cmsService.sendCartRecoveryEmail(id);
      showToast(`Cart recovery email sent to ${updated.customerEmail}!`, 'success');
      await loadData();
    } catch (err: any) {
      showToast(err.message || 'Failed to send recovery email.', 'error');
    } finally {
      setIsSaving(false);
    }
  };

  // PIXELS UPDATE
  const handleSavePixels = async (e: React.FormEvent) => {
    e.preventDefault();
    setIsSaving(true);
    try {
      await cmsService.updatePixelConfig(pixelConfig);
      showToast('Tracking pixels configuration updated!', 'success');
      await loadData();
    } catch (err: any) {
      showToast(err.message || 'Failed to update pixels.', 'error');
    } finally {
      setIsSaving(false);
    }
  };

